// ── CreatorProfile ─────────────────────────────────────────────────────────────

export interface PlatformDetail {
  name: string;             // "instagram"|"youtube"|"tiktok"|"twitter"|"linkedin"
  handle: string;
  url: string | null;
  follower_count: number | null;   // fictional demo data; not a verified statistic
}

export interface PortfolioItem {
  id: string;
  title: string;
  description: string;
  platform: string;
  content_url: string | null;
  thumbnail_url: string | null;
  tags: string[];
}

export interface CreatorProfile {
  id: string;
  display_name: string;
  handle: string;
  bio: string;
  skills: string[];
  ai_tools: string[];
  niches: string[];
  platforms: PlatformDetail[];
  portfolio_items: PortfolioItem[];
  style_tags: string[];
  starting_price: number;
  currency: string;
  availability: boolean;
  portfolio_evidence: string;
  created_at: string;
}

// ── CampaignBrief ──────────────────────────────────────────────────────────────

export type BriefGeneratedBy =
  | "gemini"          // All editable fields generated by Gemini
  | "gemini_partial"  // Some fields generated; user-edited fields preserved
  | "gemini_raw"      // Parse failure; raw_text available
  | "mock"            // Deterministic mock provider
  | "user";           // No AI generation yet

export type CampaignStatus =
  | "draft"
  | "brief_ready"
  | "matches_ready"
  | "shortlisted"
  | "completed";

export interface CampaignBrief {
  id: string;
  brand_name: string;           // Immutable after creation
  product_description: string;  // Immutable after creation
  target_audience: string;      // Immutable after creation
  budget_min: number;           // Immutable; never changed by Gemini
  budget_max: number;           // Immutable; never changed by Gemini
  currency: string;             // Immutable; never changed by Gemini
  deadline: string | null;      // Immutable; never changed by Gemini
  campaign_title: string;
  objective: string;
  deliverables: string[];
  preferred_platforms: string[];
  required_skills: string[];
  preferred_niches: string[];
  preferred_style: string;
  tone: string;
  key_messages: string[];
  call_to_action: string;
  generated_by: BriefGeneratedBy;
  user_edited_fields: string[];  // Tracks which editable fields the user has manually changed
  status: CampaignStatus;
  created_at: string;
}

// ── CampaignWorkflow ───────────────────────────────────────────────────────────

export type WorkflowStatus =
  | "draft"
  | "brief_ready"
  | "matches_ready"
  | "shortlisted"
  | "completed";

export interface CampaignWorkflow {
  id: string;
  campaign_id: string;
  selected_creator_ids: string[];
  workflow_status: WorkflowStatus;
  created_at: string;
  updated_at: string;
}

// ── MatchResult ────────────────────────────────────────────────────────────────

export interface ScoreBreakdown {
  skill_niche_relevance: number;   // 0.0–1.0  weight 35%
  portfolio_relevance: number;     // 0.0–1.0  weight 25%
  style_compatibility: number;     // 0.0–1.0  weight 20%
  budget_fit: number;              // 0.0–1.0  weight 10%
  availability: number;            // 0.0–1.0  weight 10%
}

export interface MatchResult {
  campaign_id: string;
  creator_id: string;
  creator: CreatorProfile;
  total_score: number;           // 0.00–100.00
  score_breakdown: ScoreBreakdown;
  evidence: Record<string, string[]>;
  explanation: string;
  budget_fit: boolean;
  over_budget: boolean;          // UI must display a visible red "Over budget" badge
  availability_fit: boolean;
  matched_at: string;
}

// ── API response shapes ────────────────────────────────────────────────────────

export interface CampaignDetail {
  brief: CampaignBrief;
  workflow: CampaignWorkflow;
}

export interface BriefGenerationResponse {
  brief: CampaignBrief;
  source: "gemini" | "gemini_partial" | "gemini_raw" | "mock";
  model: string | null;
  warning?: string;
  raw_text?: string;
}

export interface MatchResponse {
  results: MatchResult[];
  campaign_id: string;
  matched_at: string;
  total_evaluated: number;
}

export interface HealthResponse {
  status: "ok";
  gemini_available: boolean;
  gemini_model: string | null;
  source: "gemini" | "mock";
  mock_reason?: string;
}

export interface ApiError {
  error: string;
  code: string;
  details: Record<string, unknown>;
}
