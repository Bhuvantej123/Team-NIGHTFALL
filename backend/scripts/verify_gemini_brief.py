"""
backend/scripts/verify_gemini_brief.py
Live verification of Gemini brief generation and Supabase persistence.
P1 owns all changes.
"""

import json
import os
import sys
from pathlib import Path

# Ensure project root is importable
_PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from backend.config import load_environment
from backend.scripts.init_supabase_db import mask_db_url
load_environment()

from backend.app import create_app
from backend.models.database import get_session
from backend.models.campaign_model import CampaignBriefModel, CampaignWorkflowModel


def verify_live_gemini():
    print("\n" + "=" * 60)
    print("CreatorConnect AI — Live Gemini & Supabase Verification")
    print("=" * 60)

    # 1. Check environment variables
    api_key = os.getenv("GEMINI_API_KEY")
    model_name = os.getenv("GEMINI_MODEL")
    db_url = os.getenv("DATABASE_URL")

    print(f"[ENV] GEMINI_API_KEY configured : {bool(api_key and api_key != 'your-gemini-api-key-here')}")
    print(f"[ENV] GEMINI_MODEL configured   : {model_name or '<empty>'}")
    print(f"[ENV] Target Database           : {mask_db_url(db_url or '<empty>')}")

    if not api_key or api_key == "your-gemini-api-key-here":
        print("\n[ERROR] GEMINI_API_KEY is missing or placeholder. Aborting.")
        sys.exit(1)

    if not model_name:
        print("\n[ERROR] GEMINI_MODEL is not configured. Aborting.")
        sys.exit(1)

    # 2. Initialize application
    print("\n[APP] Bootstrapping Flask application with live providers...")
    app = create_app()

    provider = app.config.get("BRIEF_PROVIDER")
    source_label = provider.source_label() if provider else "none"
    print(f"[APP] Active BriefProvider      : {type(provider).__name__} (source: '{source_label}')")

    if source_label != "gemini":
        print(f"\n[FAIL] Provider is '{source_label}', not 'gemini'. Mock fallback active: {app.config.get('MOCK_REASON')}")
        sys.exit(1)

    client = app.test_client()

    # 3. Create a real campaign record via API
    print("\n[STEP 1] Creating a new campaign via POST /api/campaigns...")
    campaign_payload = {
        "brand_name": "Lumina Skincare",
        "product_description": "Clean-label peptide hydrating serum with marine algae extract for sensitive skin.",
        "target_audience": "Millennials and Gen Z seeking sustainable, cruelty-free clinical skincare.",
        "budget_min": 1500.0,
        "budget_max": 4500.0,
        "currency": "USD",
        "deadline": "2026-11-30",
    }

    create_res = client.post("/api/campaigns", json=campaign_payload)
    if create_res.status_code != 201:
        print(f"[FAIL] POST /api/campaigns returned HTTP {create_res.status_code}: {create_res.get_json()}")
        sys.exit(1)

    create_data = create_res.get_json()
    campaign_id = create_data["id"]
    print(f"[OK] Campaign created with ID: {campaign_id}")
    print(f"     Initial status: '{create_data.get('status')}', generated_by: '{create_data.get('generated_by')}'")

    # 4. Generate campaign brief using live Gemini
    import time
    print(f"\n[STEP 2] Calling POST /api/campaigns/{campaign_id}/generate-brief with Gemini...")
    max_retries = 3
    gen_res = None
    for attempt in range(1, max_retries + 1):
        gen_res = client.post(f"/api/campaigns/{campaign_id}/generate-brief")
        if gen_res.status_code == 200:
            break
        print(f"     [RETRY] Attempt {attempt} returned HTTP {gen_res.status_code}. Retrying in 4s...")
        time.sleep(4)

    if gen_res.status_code != 200:
        print(f"[FAIL] POST /api/campaigns/{campaign_id}/generate-brief failed (HTTP {gen_res.status_code}): {gen_res.get_json()}")
        sys.exit(1)

    gen_data = gen_res.get_json()
    returned_source = gen_data.get("source")
    returned_model = gen_data.get("model")
    brief = gen_data.get("brief", {})

    print(f"[OK] Brief generation responded HTTP 200")
    print(f"     Source : '{returned_source}'")
    print(f"     Model  : '{returned_model}'")

    # Confirm provider used is Gemini, not MockProvider
    if returned_source not in ("gemini", "gemini_partial"):
        print(f"\n[FAIL] Brief was NOT generated by Gemini. Source returned: '{returned_source}'")
        if "warning" in gen_data:
            print(f"       Warning: {gen_data['warning']}")
        sys.exit(1)

    # 5. Validate generated brief's required fields
    print("\n[STEP 3] Validating generated brief fields...")
    required_fields = [
        "campaign_title", "objective", "deliverables", "preferred_platforms",
        "required_skills", "preferred_niches", "preferred_style", "tone",
        "key_messages", "call_to_action"
    ]

    for f in required_fields:
        val = brief.get(f)
        is_valid = bool(val)
        status_sym = "[OK]" if is_valid else "[FAIL]"
        if isinstance(val, list):
            preview = f"[{len(val)} items]: {', '.join(str(x) for x in val[:3])}"
        else:
            preview = f"'{val[:60]}...'" if len(str(val)) > 60 else f"'{val}'"
        print(f"  {status_sym} {f:<22} : {preview}")
        assert is_valid, f"Required field '{f}' is empty or missing"

    # Verify immutable fields preserved
    assert brief["brand_name"] == campaign_payload["brand_name"]
    assert brief["budget_min"] == campaign_payload["budget_min"]
    assert brief["budget_max"] == campaign_payload["budget_max"]
    assert brief["status"] == "brief_ready"
    assert brief["generated_by"] in ("gemini", "gemini_partial")
    print("[OK] All required and immutable fields validated successfully.")

    # 6. Verify persistence in Supabase
    print("\n[STEP 4] Verifying database persistence in Supabase PostgreSQL...")
    with get_session() as session:
        persisted = session.get(CampaignBriefModel, campaign_id)
        if persisted is None:
            print(f"[FAIL] Campaign '{campaign_id}' not found in Supabase database!")
            sys.exit(1)

        print(f"[OK] Record verified in Supabase:")
        print(f"     ID           : {persisted.id}")
        print(f"     Status       : {persisted.status}")
        print(f"     Generated By : {persisted.generated_by}")
        print(f"     Title        : {persisted.campaign_title}")
        print(f"     Objective    : {persisted.objective[:80]}...")
        print(f"     Deliverables : {persisted.deliverables}")
        print(f"     Platforms    : {persisted.preferred_platforms}")

        workflow = session.query(CampaignWorkflowModel).filter(
            CampaignWorkflowModel.campaign_id == campaign_id
        ).first()
        if workflow:
            print(f"     Workflow ID  : {workflow.id} (status: '{workflow.workflow_status}')")

    print("\n" + "=" * 60)
    print("SUCCESS: Live Gemini brief generation & Supabase persistence VERIFIED.")
    print("=" * 60 + "\n")


if __name__ == "__main__":
    verify_live_gemini()
